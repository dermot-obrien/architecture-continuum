/**
 * The assessment criteria register, published: one Markdown page per criterion, one per lens,
 * and an index of every criterion, generated from standards/assessment/lenses/*.yaml into
 * docs/assessment-criteria/. Each page's file name is its criterion id in lower case, so a
 * Docusaurus site gives every criterion a stable URL, <site>/<docs path>/assessment-criteria/core-tgt-05,
 * that reports and readouts link to (the report flow's criteriaUrl binding). The lens files are the
 * register and stay the source; the pages are never edited by hand.
 *
 *   node scripts/generate-criteria-pages.mjs           write the pages
 *   node scripts/generate-criteria-pages.mjs --check   fail if any page is missing, stale or orphaned
 */

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const yaml = require("js-yaml");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lensDir = join(root, "standards/assessment/lenses");
const outDir = join(root, "docs/assessment-criteria");
const check = process.argv.includes("--check");
if (process.argv.some(a => a === "--help" || a === "-h")) {
  console.log("usage: node scripts/generate-criteria-pages.mjs [--check]");
  process.exit(0);
}

const ORDER = ["core", "ai-solution", "ai-agent", "production"];
const DECIDER = { tool: "A tool, by its rule", both: "A tool checks presence; a reviewer judges", reviewer: "A reviewer" };
const lenses = readdirSync(lensDir).filter(f => f.endsWith(".yaml"))
  .map(f => yaml.load(readFileSync(join(lensDir, f), "utf8")))
  .sort((a, b) => (ORDER.indexOf(a.lens.id) + 99) % 99 - (ORDER.indexOf(b.lens.id) + 99) % 99 || a.lens.id.localeCompare(b.lens.id));

const slug = id => id.toLowerCase();
const esc = s => String(s ?? "").replace(/\s+/g, " ").trim();
const cell = s => esc(s).replace(/\|/g, "\\|");
const appliesWhen = l => l.lens.applies_when === "always" ? "always"
  : l.lens.applies_when.profile ? `designs with the \`${l.lens.applies_when.profile}\` profile`
  : `the \`${Object.values(l.lens.applies_when)[0]}\` assessment`;
const fm = (title, extra = "") => `---\ntitle: "${title.replace(/"/g, '\\"')}"\n${extra}---\n\n<!-- Generated by scripts/generate-criteria-pages.mjs from standards/assessment/lenses/. Do not edit. -->\n\n`;

const pages = new Map();
const all = [];

for (const l of lenses) {
  const areas = new Map((l.areas || []).map(a => [a.id, a]));
  const sources = l.sources || {};
  let lensPage = fm(`${l.lens.title}`, `sidebar_label: "${l.lens.id}"\n`) +
    `# ${l.lens.title} ${l.lens.version}\n\n${esc(l.lens.description)}\n\nApplies to ${appliesWhen(l)}. Source: [\`standards/assessment/lenses/${l.lens.id}.yaml\`](../../standards/assessment/lenses/${l.lens.id}.yaml).\n\n`;
  for (const a of l.areas || []) {
    const crit = l.criteria.filter(c => c.area === a.id);
    if (!crit.length) continue;
    lensPage += `## ${a.id}: ${a.title}\n\n${esc(a.question)}\n\n| Criterion | Question | Severity | Decided by |\n|---|---|---|---|\n` +
      crit.map(c => `| [${c.id}](${slug(c.id)}.md) | ${cell(c.question)} | ${c.severity} | ${c.decided_by} |`).join("\n") + "\n\n";
  }
  pages.set(`${l.lens.id}.md`, lensPage);

  for (const c of l.criteria) {
    const area = areas.get(c.area);
    all.push({ c, l, area });
    let p = fm(`${c.id}: ${esc(c.question)}`, `sidebar_label: "${c.id}"\n`) +
      `# ${c.id}\n\n**${esc(c.question)}**\n\n` +
      `| | |\n|---|---|\n` +
      `| Lens | [${l.lens.title}](${l.lens.id}.md) ${l.lens.version} |\n` +
      `| Area | ${area ? `${area.id}: ${cell(area.title)}` : c.area} |\n` +
      `| Default severity | ${c.severity} |\n` +
      `| Decided by | ${DECIDER[c.decided_by] || c.decided_by} |\n` +
      (c.applies_to ? `| Applies when | ${cell(c.applies_to)} |\n` : "") +
      (c.reads?.length ? `| Reads | ${c.reads.map(r => `\`${r}\``).join(", ")} |\n` : "") + "\n";
    if (c.why) p += `## Why it matters\n\n${esc(c.why)}\n\n`;
    if (c.rule) p += `## Rule\n\n${esc(c.rule)}\n\n`;
    if (c.sources?.length) p += `## Sources\n\n` + c.sources.map(s => `- ${sources[s] ? `${esc(sources[s])} (\`${s}\`)` : `\`${s}\``}`).join("\n") + "\n\n";
    p += `Defined in [\`standards/assessment/lenses/${l.lens.id}.yaml\`](../../standards/assessment/lenses/${l.lens.id}.yaml). How results, findings and outcomes work: the [Architecture Assessment Standard](../../standards/assessment/standard-architecture-assessment.md).\n`;
    pages.set(`${slug(c.id)}.md`, p);
  }
}

const count = (f) => all.filter(f).length;
let index = fm("Assessment criteria", `sidebar_label: "Criteria register"\nsidebar_position: 1\n`) +
  `# Assessment criteria\n\nEvery criterion of the [Architecture Assessment Standard](../../standards/assessment/standard-architecture-assessment.md), ${all.length} in ${lenses.length} lenses, ${count(x => x.c.severity === "blocker")} of them blockers. Each has its own page, named by its id in lower case, so its URL is stable and a report can link straight to it. The lens files in \`standards/assessment/lenses/\` are the register, valid against \`lens.schema.json\`; these pages are generated from them.\n\n` +
  `| Lens | Version | Applies to | Criteria | Blockers |\n|---|---|---|---|---|\n` +
  lenses.map(l => `| [${l.lens.title}](${l.lens.id}.md) | ${l.lens.version} | ${appliesWhen(l)} | ${l.criteria.length} | ${l.criteria.filter(c => c.severity === "blocker").length} |`).join("\n") +
  `\n\n## Every criterion\n\n| Criterion | Question | Lens | Severity | Decided by |\n|---|---|---|---|---|\n` +
  all.map(({ c, l }) => `| [${c.id}](${slug(c.id)}.md) | ${cell(c.question)} | ${l.lens.id} | ${c.severity} | ${c.decided_by} |`).join("\n") + "\n";
pages.set("index.md", index);

if (check) {
  const problems = [];
  for (const [name, text] of pages) {
    const p = join(outDir, name);
    if (!existsSync(p)) problems.push(`missing ${name}`);
    else if (readFileSync(p, "utf8") !== text) problems.push(`stale ${name}`);
  }
  if (existsSync(outDir)) for (const f of readdirSync(outDir)) if (f.endsWith(".md") && !pages.has(f)) problems.push(`orphaned ${f}`);
  if (problems.length) {
    console.error(problems.join("\n") + `\nRun node scripts/generate-criteria-pages.mjs and commit docs/assessment-criteria/.`);
    process.exit(1);
  }
  console.log(`criteria pages are up to date (${pages.size} pages)`);
} else {
  if (existsSync(outDir)) for (const f of readdirSync(outDir)) if (f.endsWith(".md") && !pages.has(f)) rmSync(join(outDir, f));
  mkdirSync(outDir, { recursive: true });
  for (const [name, text] of pages) writeFileSync(join(outDir, name), text);
  console.log(`wrote ${pages.size} pages to docs/assessment-criteria/`);
}

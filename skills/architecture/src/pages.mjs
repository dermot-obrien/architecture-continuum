/**
 * The criteria register, published: one Markdown page per criterion, one per lens, and an index,
 * from the lenses in force. Each page's file name is its criterion id in lower case, so a
 * Docusaurus site gives every criterion a stable URL that reports and readouts link to (the
 * criteriaUrl binding). The lens files are the register and stay the source; the pages are never
 * edited by hand.
 *
 * Used by `assess.mjs pages` for an organisation's criteria, and by this bundle's
 * scripts/generate-criteria-pages.mjs for the shipped ones.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const SHIPPED_SOURCE = "https://github.com/dermot-obrien/architecture-continuum/blob/main/standards/assessment";
const ORDER = ["core", "ai-solution", "ai-agent", "production"];
const DECIDER = { tool: "A tool, by its rule", both: "A tool checks presence; a reviewer judges", reviewer: "A reviewer" };

const posix = p => p.split(path.sep).join("/");
const slug = id => id.toLowerCase();
const esc = s => String(s ?? "").replace(/\s+/g, " ").trim();
const cell = s => esc(s).replace(/\|/g, "\\|");
const appliesWhen = l => l.lens.applies_when === "always" ? "always"
  : l.lens.applies_when.profile ? `designs with the \`${l.lens.applies_when.profile}\` profile`
  : `the \`${Object.values(l.lens.applies_when)[0]}\` assessment`;

/**
 * The pages, as a Map of file name to text. Options:
 *   outDir         where the pages go, for relative links to the sources
 *   lensLink(l)    { href, label } for a lens's source file (default: relative to outDir, or the
 *                  bundle's published source for a shipped lens read from an installed skill)
 *   standardHref   the assessment standard the pages cite (default: the bundle's published one)
 *   generatedBy    who wrote the pages, for the do-not-edit comment
 *   title, intro   the index's title and opening sentence, before the counts
 *   registerNote   the sentence saying where the register lives
 *   dump(v)        YAML for a declarative check (default: JSON, which is YAML too)
 */
export function criteriaPages(lenses, opts = {}) {
  const outDir = opts.outDir ?? ".";
  const lensLink = opts.lensLink ?? (l => l.builtin === false
    ? { href: posix(path.relative(outDir, l.file)), label: path.basename(l.file) }
    : { href: `${SHIPPED_SOURCE}/lenses/${l.lens.id}.yaml`, label: `${l.lens.id}.yaml (architecture-continuum)` });
  const standardHref = opts.standardHref ?? `${SHIPPED_SOURCE}/standard-architecture-assessment.md`;
  const generatedBy = opts.generatedBy ?? "assess.mjs pages from the lenses in force";
  const dump = opts.dump ?? (v => JSON.stringify(v, null, 2));
  const fm = (title, extra = "") => `---\ntitle: "${title.replace(/"/g, '\\"')}"\n${extra}---\n\n<!-- Generated by ${generatedBy}. Do not edit. -->\n\n`;
  const sorted = [...lenses].sort((a, b) => (ORDER.indexOf(a.lens.id) + 99) % 99 - (ORDER.indexOf(b.lens.id) + 99) % 99 || a.lens.id.localeCompare(b.lens.id));

  const pages = new Map();
  const all = [];
  for (const l of sorted) {
    const areas = new Map((l.areas || []).map(a => [a.id, a]));
    const sources = l.sources || {};
    const src = lensLink(l);
    const defined = `[\`${src.label}\`](${src.href})`;
    let lensPage = fm(`${l.lens.title}`, `sidebar_label: "${l.lens.id}"\n`) +
      `# ${l.lens.title} ${l.lens.version}\n\n${esc(l.lens.description)}\n\nApplies to ${appliesWhen(l)}. Source: ${defined}.\n\n`;
    for (const a of l.areas || []) {
      const crit = l.criteria.filter(c => c.area === a.id);
      if (!crit.length) continue;
      lensPage += `## ${a.id}: ${a.title}\n\n${esc(a.question)}\n\n| Criterion | Question | Severity | Decided by |\n|---|---|---|---|\n` +
        crit.map(c => `| [${c.id}](${slug(c.id)}.md) | ${cell(c.question)} | ${c.severity} | ${c.decided_by} |`).join("\n") + "\n\n";
    }
    pages.set(`${l.lens.id}.md`, lensPage);

    for (const c of l.criteria) {
      const area = areas.get(c.area);
      all.push({ c, l, area });
      const severity = c.default_severity
        ? `${c.severity} (the organisation's; the lens says ${c.default_severity}${c.organisation_note ? `: ${cell(c.organisation_note)}` : ""})`
        : `${c.severity}${c.organisation_note ? ` (${cell(c.organisation_note)})` : ""}`;
      let p = fm(`${c.id}: ${esc(c.question)}`, `sidebar_label: "${c.id}"\n`) +
        `# ${c.id}\n\n**${esc(c.question)}**\n\n` +
        `| | |\n|---|---|\n` +
        `| Lens | [${l.lens.title}](${l.lens.id}.md) ${l.lens.version} |\n` +
        `| Area | ${area ? `${area.id}: ${cell(area.title)}` : c.area} |\n` +
        `| Default severity | ${severity} |\n` +
        `| Decided by | ${DECIDER[c.decided_by] || c.decided_by} |\n` +
        (c.applies_to ? `| Applies when | ${cell(c.applies_to)} |\n` : "") +
        (c.reads?.length ? `| Reads | ${c.reads.map(r => `\`${r}\``).join(", ")} |\n` : "") + "\n";
      if (c.why) p += `## Why it matters\n\n${esc(c.why)}\n\n`;
      if (c.rule) p += `## Rule\n\n${esc(c.rule)}\n\n`;
      if (c.check) p += `## Check\n\nThe tool applies this rule as written:\n\n\`\`\`yaml\n${dump(c.check).trimEnd()}\n\`\`\`\n\n`;
      if (c.sources?.length) p += `## Sources\n\n` + c.sources.map(s => `- ${sources[s] ? `${esc(sources[s])} (\`${s}\`)` : `\`${s}\``}`).join("\n") + "\n\n";
      p += `Defined in ${defined}. How results, findings and outcomes work: the [Architecture Assessment Standard](${standardHref}).\n`;
      pages.set(`${slug(c.id)}.md`, p);
    }
  }

  const count = (f) => all.filter(f).length;
  const intro = opts.intro ?? `Every criterion of the [Architecture Assessment Standard](${standardHref})`;
  const index = fm(opts.title ?? "Assessment criteria", `sidebar_label: "Criteria register"\nsidebar_position: 1\n`) +
    `# ${opts.title ?? "Assessment criteria"}\n\n${intro}, ${all.length} in ${sorted.length} lenses, ${count(x => x.c.severity === "blocker")} of them blockers. Each has its own page, named by its id in lower case, so its URL is stable and a report can link straight to it. ${opts.registerNote ?? "The lens files are the register, valid against `lens.schema.json`; these pages are generated from them."}\n\n` +
    `| Lens | Version | Applies to | Criteria | Blockers |\n|---|---|---|---|---|\n` +
    sorted.map(l => `| [${l.lens.title}](${l.lens.id}.md) | ${l.lens.version} | ${appliesWhen(l)} | ${l.criteria.length} | ${l.criteria.filter(c => c.severity === "blocker").length} |`).join("\n") +
    `\n\n## Every criterion\n\n| Criterion | Question | Lens | Severity | Decided by |\n|---|---|---|---|---|\n` +
    all.map(({ c, l }) => `| [${c.id}](${slug(c.id)}.md) | ${cell(c.question)} | ${l.lens.id} | ${c.severity} | ${c.decided_by} |`).join("\n") + "\n";
  pages.set("index.md", index);
  return pages;
}

/** Write the pages to outDir, removing orphans; or, with check, list what is missing, stale or orphaned. */
export function writePages(pages, outDir, { check = false } = {}) {
  if (check) {
    const problems = [];
    for (const [name, text] of pages) {
      const p = path.join(outDir, name);
      if (!existsSync(p)) problems.push(`missing ${name}`);
      else if (readFileSync(p, "utf8") !== text) problems.push(`stale ${name}`);
    }
    if (existsSync(outDir)) for (const f of readdirSync(outDir)) if (f.endsWith(".md") && !pages.has(f)) problems.push(`orphaned ${f}`);
    return problems;
  }
  if (existsSync(outDir)) for (const f of readdirSync(outDir)) if (f.endsWith(".md") && !pages.has(f)) rmSync(path.join(outDir, f));
  mkdirSync(outDir, { recursive: true });
  for (const [name, text] of pages) writeFileSync(path.join(outDir, name), text);
  return [];
}
